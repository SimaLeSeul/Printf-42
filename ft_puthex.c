#include "ft_printf.h"

int	ft_puthex(unsigned int n)
{
	int		i;
	char	*hex;

	i = 0;
	hex = "0123456789abcdef";
	if (n > 15)
		i += ft_puthex(n / 16);
	i += ft_putchar(hex[n % 16]);
	return (i);
}
